"""The lexicon the runtime grammar's verb filler resolves through: verb lemma -> rolesets, (rolesets, wh) -> roles.

The grammar holds no construction per roleset (a bonfire has hundreds; FCG's latency grows with the inventory). The
normaliser marks verbs ("⟪work⟫"), one base filler reads the marked lemma, and the executor resolves it with two ops:

* ``frames-of(?fs ← lemma)``: the bonfire's rolesets whose lemma (the id before the ``.``) is ``lemma`` (from the
  bonfire's ``chain/rolesets.json``), else the question map's rolesets for that lemma; verb-sense ambiguity travels on
  as the whole set;
* ``wh-role(?r ← ?fs, wh)``: the ``(frame, role)`` pairs that answer ``wh`` in those frames, from the question map;
* ``role-kinds(?k ← ?r)``: the store kinds (``KIND_LABELS``) of the entities that fill those roles, from the map's
  per-role labels (VerbNet themes -> store kinds): per frame, its own roles' kinds, else (no own role among the pairs)
  the shared modifiers' kinds. The state path of a wh root reads only entities of these kinds.

The question map (``data/runtime-grammar/question-map.json``, generated by ``scripts/build_question_map.py`` from the
PropBank frame files' function tags and VerbNet themes) is ``{roleset: [[wh, role], ...]}`` plus the shared ``"*"``
entry, the modifiers every frame admits; a role whose themes have store kinds is ``[wh, role, [label, ...]]``. A wh label joining two kinds with ``_or_`` (``who_or_what``: the frame files
cannot tell a person from a thing; the filler's kind label does, at execution) answers a question for either kind;
``unknown`` (a role the tags cannot settle) answers none.

``CompositeMemory`` puts the lexicon beside the store: one ``MemoryOps`` that routes each op to the first part whose
specs name it.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping, Sequence
from importlib import resources
from pathlib import Path
from typing import Any

from memory_kernel.graph.g1_names import KIND_LABELS
from memory_kernel.runtime.executor import MemoryOps
from memory_kernel.runtime.program import OpSpec

#: the key of the modifiers every frame admits
SHARED = "*"
#: the label of a role the frame files cannot settle; it answers no question
UNKNOWN = "unknown"
#: joins two question kinds in one label (``who_or_what``)
_EITHER = "_or_"
_SHIPPED = ("data", "runtime-grammar", "question-map.json")

LEXICON_SPECS: Mapping[str, OpSpec] = {
    spec.name: spec
    for spec in (
        OpSpec("frames-of", ("lemma",), ("frames",), "memory"),
        OpSpec("wh-role", ("frames", "wh"), ("roles",), "memory"),
        OpSpec("role-kinds", ("roles",), ("kinds",), "memory"),
    )
}


def _answers(label: str, wh: str) -> bool:
    if label == UNKNOWN:
        return False
    return label == wh or wh in label.split(_EITHER)


class QuestionMap:
    """Which roles of a roleset answer which kind of question."""

    def __init__(self, entries: Mapping[str, Sequence[Sequence[str]]]) -> None:
        self._entries: dict[str, tuple[tuple[str, str], ...]] = {}
        self._kinds: dict[tuple[str, str], tuple[str, ...]] = {}
        for roleset, pairs in entries.items():
            if not isinstance(roleset, str) or not isinstance(pairs, Sequence):
                raise ValueError(f"question map entry {roleset!r} is not roleset -> [[wh, role], ...]")
            parsed: list[tuple[str, str]] = []
            for pair in pairs:
                if len(pair) not in (2, 3) or not all(isinstance(x, str) and x for x in pair[:2]):
                    raise ValueError(f"question map entry {roleset!r}: {pair!r} is not [wh, role(, labels)]")
                parsed.append((pair[0], pair[1]))
                if len(pair) == 3:
                    labels = pair[2]
                    if isinstance(labels, str) or not isinstance(labels, Sequence) or not labels:
                        raise ValueError(f"question map entry {roleset!r}: {pair!r} has no kind list")
                    unknown = [x for x in labels if x not in KIND_LABELS]
                    if unknown:
                        raise ValueError(f"question map entry {roleset!r}: kind {unknown} is not in {KIND_LABELS}")
                    self._kinds[(roleset, pair[1])] = tuple(labels)
            self._entries[roleset] = tuple(parsed)
        self._by_lemma: dict[str, list[str]] = {}
        for roleset in sorted(self._entries):
            if roleset != SHARED and not self.roleless(roleset):
                self._by_lemma.setdefault(_lemma_of(roleset), []).append(roleset)

    @classmethod
    def load(cls, path: Path | None = None) -> QuestionMap:
        """The map at ``path``, by default the one shipped in the package."""
        if path is None:
            text = resources.files("memory_kernel").joinpath(*_SHIPPED).read_text(encoding="utf-8")
        else:
            text = Path(path).read_text(encoding="utf-8")
        return cls(json.loads(text))

    def rolesets(self) -> list[str]:
        """Every roleset the map holds (not the shared entry), sorted."""
        return sorted(r for r in self._entries if r != SHARED)

    def rolesets_of(self, lemma: str) -> list[str]:
        """The rolesets of ``lemma`` that have roles (a roleless roleset, such as a light-verb ``*.LV`` entry, answers
        no question and is never offered)."""
        return list(self._by_lemma.get(lemma, ()))

    def roleless(self, roleset: str) -> bool:
        """The map holds ``roleset`` with no role at all (a structural test: an empty entry, whatever the id)."""
        return roleset in self._entries and not self._entries[roleset]

    def pairs(self, roleset: str) -> list[tuple[str, str]]:
        """The roleset's own ``(wh, role)`` pairs, as stored (no shared modifiers)."""
        return list(self._entries.get(roleset, ()))

    def kinds(self, roleset: str, role: str) -> tuple[str, ...]:
        """The store kinds of the entities that fill ``role`` of ``roleset`` (``"*"`` for a shared modifier); () when
        the map gives none."""
        return self._kinds.get((roleset, role), ())

    def roles(self, roleset: str, wh: str) -> list[str]:
        """The roles of ``roleset`` answering ``wh``, its own first, then the shared modifiers; no duplicates."""
        out: list[str] = []
        for label, role in (*self._entries.get(roleset, ()), *self._entries.get(SHARED, ())):
            if _answers(label, wh) and role not in out:
                out.append(role)
        return out


def _lemma_of(roleset: str) -> str:
    return roleset.split(".", 1)[0]


class Lexicon:
    """The bonfire's rolesets over the question map."""

    def __init__(self, rolesets: Iterable[str], question_map: QuestionMap) -> None:
        self.question_map = question_map
        self._by_lemma: dict[str, list[str]] = {}
        for roleset in sorted(set(rolesets)):
            if not question_map.roleless(roleset):
                self._by_lemma.setdefault(_lemma_of(roleset), []).append(roleset)

    def frames_of(self, lemma: str) -> list[str]:
        """The bonfire's rolesets of ``lemma``; if it has none, the question map's; sorted. A roleset the map holds
        with no role is never returned."""
        key = lemma.strip().lower()
        return list(self._by_lemma.get(key) or self.question_map.rolesets_of(key))

    def wh_roles(self, frames: Sequence[str], wh: str) -> list[tuple[str, str]]:
        """The ``(frame, role)`` pairs answering ``wh``, in frame order."""
        return [(frame, role) for frame in frames for role in self.question_map.roles(frame, wh)]

    def role_kinds(self, pairs: Iterable[Sequence[str]]) -> list[str]:
        """The store kinds of the ``(frame, role)`` pairs (``wh_roles``' output), sorted: per frame, the kinds of its
        own roles among the pairs; a frame with no own role among them takes the shared modifiers' kinds."""
        qm = self.question_map
        by_frame: dict[str, list[str]] = {}
        for frame, role in pairs:
            by_frame.setdefault(frame, []).append(role)
        out: set[str] = set()
        for frame, roles in by_frame.items():
            own = {role for _, role in qm.pairs(frame)}
            mine = [role for role in roles if role in own]
            for role in mine or roles:
                out.update(qm.kinds(frame, role) if mine else qm.kinds(SHARED, role))
        return sorted(out)


def load_rolesets(driver: Any, group: str) -> list[str]:
    """The rolesets of a bonfire: the ``roleset`` of its ``Roleset`` nodes in ``group``, sorted. ``driver`` is a sync
    Neo4j driver."""
    from memory_kernel.runtime.graph_store import READ_ROLESETS

    with driver.session() as session:
        return sorted(str(r["roleset"]) for r in session.run(READ_ROLESETS, g=group))


def _need(args: Mapping[str, Any], op: str, key: str) -> Any:
    if args.get(key) is None:
        raise ValueError(f"{op} needs its {key!r} input")
    return args[key]


class LexiconOps(MemoryOps):
    """The lexicon ops (``LEXICON_SPECS``) over one :class:`Lexicon`."""

    specs = LEXICON_SPECS

    def __init__(self, lexicon: Lexicon) -> None:
        self.lexicon = lexicon

    async def run(self, op: str, args: Mapping[str, Any]) -> Any:
        if op == "frames-of":
            return self.lexicon.frames_of(str(_need(args, op, "lemma")))
        if op == "wh-role":
            frames = _need(args, op, "frames")
            frames = [frames] if isinstance(frames, str) else [str(f) for f in frames]
            return self.lexicon.wh_roles(frames, str(_need(args, op, "wh")))
        if op == "role-kinds":
            pairs = []
            for item in _need(args, op, "roles"):
                if not (isinstance(item, (list, tuple)) and len(item) == 2 and all(isinstance(x, str) for x in item)):
                    raise ValueError(f"role-kinds: a role is a (frame, role) pair from wh-role, got {item!r}")
                pairs.append((item[0], item[1]))
            return self.lexicon.role_kinds(pairs)
        raise KeyError(f"unknown lexicon operation {op!r}")


class CompositeMemory(MemoryOps):
    """Routes each op to the first part whose specs name it (``[(MEMORY_SPECS, store), (LEXICON_SPECS, lexicon)]``).

    Two parts may name the same op only with the same spec (the first part then serves it); a name defined
    differently by two parts is refused (``ValueError``): the program's registry could not say which one it calls."""

    def __init__(self, parts: Sequence[tuple[Mapping[str, OpSpec], MemoryOps]]) -> None:
        self.parts = tuple(parts)
        seen: dict[str, OpSpec] = {}
        for specs, _ in self.parts:
            for name, spec in specs.items():
                if name in seen and seen[name] != spec:
                    raise ValueError(f"op {name!r} is defined differently by two memory parts: {seen[name]} vs {spec}")
                seen.setdefault(name, spec)

    @property
    def specs(self) -> dict[str, OpSpec]:
        """Every op the parts serve, each from the first part naming it."""
        merged: dict[str, OpSpec] = {}
        for specs, _ in self.parts:
            for name, spec in specs.items():
                merged.setdefault(name, spec)
        return merged

    async def run(self, op: str, args: Mapping[str, Any]) -> Any:
        for specs, part in self.parts:
            if op in specs:
                return await part.run(op, args)
        raise KeyError(f"unknown memory operation {op!r}")


